"""Derive compact guide fields from the actual map, bait and activity rules."""
from pathlib import Path
import json
r=Path(__file__).resolve().parents[1]
c=json.loads((r/'data/species.json').read_text(encoding='utf-8'))
m=json.loads((r/'data/map.json').read_text(encoding='utf-8'))
e=json.loads((r/'data/equipment.json').read_text(encoding='utf-8'))
rows=[];hints=[]
for s in c['species']:
    d=s['game_distribution'];base=s.get('base_index',s['index'])
    day,dusk,night=d['activity_percent']
    if day==night:active='全天，晨昏稍好' if dusk>day else '全天'
    elif night>max(day,dusk):active='夜间较活跃'
    elif day>=dusk:active='白天较活跃'
    elif day*10>=dusk*9:active='白天、晨昏'
    else:active='晨昏较活跃'
    weights=d['zone_multipliers'];zone=max(m['zones'],key=lambda z:weights[z['id']])['name_zh']
    layers=d['layers'];near=d['nearshore_only']
    if layers==['bottom']:layer='近岸钓底' if near else '钓底'
    elif set(layers)=={'surface','middle'}:layer='表层、中层'
    elif 'bottom' in layers:layer='中下层、钓底'
    else:layer='表层至下层'
    baits=sorted(e['baits'][:5],key=lambda b:b['multipliers'][base],reverse=True)[:2]
    bait='、'.join(b['name_zh'] for b in baits)
    fields=[f'时段：{active}',f'水域：{zone}',f'钓层：{layer}',f'推荐：{bait}']
    rows.append(fields);hints.append('同种的稀有变异' if s.get('special_variant') else layer)
q=lambda text:json.dumps(text,ensure_ascii=False)
code='/* Generated by tools/prepare_guide.py; game rules, not real ecology. */\n#ifndef FISH_GUIDE_DATA_H\n#define FISH_GUIDE_DATA_H\n'
code+='static const char *const fish_guide_fields[FISH_SPECIES_COUNT][4]={\n'
code+=''.join('    {'+', '.join(map(q,row))+'},\n' for row in rows)+'};\n'
code+='static const char *const fish_guide_hints[FISH_SPECIES_COUNT]={\n'+''.join('    '+q(t)+',\n' for t in hints)+'};\n#endif\n'
target=r/'app' if (r/'app').exists() else r/'src/fish'
(target/'fish_guide_data.h').write_text(code,encoding='utf-8')
print(f'Prepared {len(rows)} guide entries from current activity, zones, layers and bait weights.')
