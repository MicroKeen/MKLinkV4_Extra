"""Compact 12px guide fields from current playable habitats and available baits."""
from pathlib import Path
import json
r=Path(__file__).resolve().parents[1]
read=lambda n:json.loads((r/'data'/f'{n}.json').read_text(encoding='utf-8'))
c=read('species');e=read('equipment');items=read('city_items')
city={s['index']:s for s in read('city_fish')['species']}
marine={s['index']:s for s in read('marine_fish')['species']}
names=[b['name_zh'] for b in e['baits']]+[b['name_zh'] for b in items['baits']]+[items['forage_bait']['name_zh']]
def active(v):
    day,dusk,night=v
    if day==night:return '全天，晨昏稍好' if dusk>day else '全天'
    if night>max(day,dusk):return '夜间较活跃'
    if day>=dusk:return '白天较活跃'
    return '白天、晨昏' if day*10>=dusk*9 else '晨昏较活跃'
def layer_text(layers,near=False):
    if layers==['bottom']:return '近岸钓底' if near else '钓底'
    if layers==['surface']:return '表层'
    if set(layers)=={'surface','middle'}:return '表层、中层'
    if set(layers)=={'middle','lower'}:return '中下层'
    return '中下层、钓底' if 'bottom' in layers else '表层至下层'
def bait_text(weights,available):
    picks=sorted(available,key=lambda k:(-weights[k],k))
    return '推荐：'+'、'.join(names[k] for k in picks[:2] if weights[k])
def city_weights(i):return city[i]['baits']+[b['city_weights'].get(str(i),0) for b in items['baits']]+[items['forage_bait']['city_weights'].get(str(i),0)]
rows=[];hints=[]
for s in c['species']:
    i=s['index'];base=s.get('base_index',i);d=s['game_distribution']
    layer=layer_text(d['layers'],d['nearshore_only'])
    weights=[b['multipliers'][base] for b in e['baits']] if base<11 else [0]*6
    fields=['时段：'+active(d['activity_percent']),'水域：两侧近岸' if d['nearshore_only'] else '水域：全水域','钓层：'+layer,bait_text(weights,range(6))]
    if base>=15 and base in city:fields[3]=bait_text(city_weights(base),(3,4,5,6,7,8))
    if i in marine:
        row=marine[i];where={25:'礁石边至外海',29:'近岸至外海',33:'外海至深海',35:'右侧深海',37:'外海至深海'}.get(25 if i==44 else i,'全海域')
        fields=['时段：'+active(row['activity']),'水域：'+where,'钓层：'+layer,bait_text(row['baits'],range(10))]
        if s['marine_status'].startswith('foraging'):
            sand=i in (38,40,42,47,48)
            fields=['赶海采收，每日四点刷新','地点：沙滩' if sand else '地点：礁石区','工具：铲子' if sand else '工具：撬棍','沙蚕收入饵盒' if i==47 else '留意脚边的小气泡']
        if i in (34,45):fields[2]='钓层：白天中下，夜间表中'
        if i==35:fields=['时段：暴雨期间','水域：右侧深海','钓层：中下层','特殊：满足条件时百分之一']
    rows.append(fields);hints.append('同种的稀有变异' if s.get('special_variant') else layer)
q=lambda text:json.dumps(text,ensure_ascii=False)
code='/* Generated by tools/prepare_guide.py; game rules, not real ecology. */\n#ifndef FISH_GUIDE_DATA_H\n#define FISH_GUIDE_DATA_H\n'
code+='static const char *const fish_guide_fields[FISH_SPECIES_COUNT][4]={\n'+''.join('    {'+', '.join(map(q,row))+'},\n' for row in rows)+'};\n'
code+='static const char *const fish_guide_city_fields[3][2]={'+','.join('{'+q('钓层：'+layer_text(city[i]['species']['game_distribution']['layers']))+','+q(bait_text(city_weights(i),(3,4,5,6,7,8)))+'}' for i in (0,1,7))+'};\n'
code+='static const char *const fish_guide_hints[FISH_SPECIES_COUNT]={\n'+''.join('    '+q(t)+',\n' for t in hints)+'};\n#endif\n'
target=r/'app' if (r/'app').exists() else r/'src/fish'
(target/'fish_guide_data.h').write_text(code,encoding='utf-8')
print(f'Prepared {len(rows)} guide entries; recognizable locations, all10 baits, shared city recommendations.')
