"""Export current marine habitat data without regenerating fish art or combat data."""
from pathlib import Path
import json
r=Path(__file__).resolve().parents[1]
read=lambda n:json.loads((r/'data'/f'{n}.json').read_text(encoding='utf-8'))
s=read('species')['species'];sea=read('marine_fish')['species']
bits={'surface':1,'middle':2,'lower':4,'bottom':8,'shore':16}
arr=lambda v:'{'+','.join(map(str,v))+'}'
code='/* Generated by tools/prepare_marine_habitats.py. Left-to-right coastal zones. */\n'
code+='static const struct {uint8_t encounter,layers,night_layers,activity[3],zones[5],baits[10];} marine_habitats[FISH_COAST_COUNT]={\n'
for f in sea:
    d=s[f['index']]['game_distribution']
    row=[f['encounter_weight'],sum(bits[k] for k in d['layers']),sum(bits[k] for k in f['night_layers']),arr(f['activity']),arr(f['zones']),arr(f['baits'])]
    code+='    {'+','.join(map(str,row))+'},\n'
target=r/'app' if (r/'app').exists() else r/'src/fish'
(target/'fish_marine_map.h').write_text(code+'};\n',encoding='utf-8')
print('Exported current marine habitats.')
